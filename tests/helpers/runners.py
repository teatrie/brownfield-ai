import os
import shutil
import subprocess

# Subprocess wait timeout in seconds; configurable via EVAL_RUNNER_TIMEOUT env var.
try:
    _RUNNER_TIMEOUT: int = int(os.environ.get("EVAL_RUNNER_TIMEOUT", "300"))
except ValueError:
    _RUNNER_TIMEOUT = 300

# ============================================================================
# Base Runner
# ============================================================================


class AgentRunner:
    """
    Abstract base class for all headless AI agent evaluators.
    """

    def run(self, prompt: str, workspace_path: str) -> str:
        """
        Executes a prompt inside a specified workspace and returns the console output.

        Args:
            prompt (str): The instructions to provide to the agent.
            workspace_path (str): The directory context for the agent's execution.

        Returns:
            str: The final stdout and stderr output generated by the agent.
        """
        raise NotImplementedError("Runner must implement run method")


# ============================================================================
# Copilot Runner
# ============================================================================


class CopilotRunner(AgentRunner):
    """
    Executes the @github/copilot NPM package in a headless, non-interactive environment
    for evaluating skill performance.
    """

    def run(self, prompt: str, workspace_path: str) -> str:
        """
        Executes a prompt via the Copilot CLI and returns the console output.

        Args:
            prompt (str): The instructions to provide to the agent.
            workspace_path (str): The directory context for the agent's execution.

        Returns:
            str: The final stdout output generated by the agent.
        """
        print(f"\n[Copilot Runner] Executing in {workspace_path}...")

        env = os.environ.copy()
        env.pop("AWS_PROFILE", None)
        env.pop("AWS_DEFAULT_PROFILE", None)
        env["CI"] = "true"
        env["GH_PAGER"] = ""
        env["GH_PROMPT_DISABLED"] = "1"
        env["NO_COLOR"] = "1"
        env["PWD"] = workspace_path

        if "PYTHONPATH" not in env:
            raise OSError("PYTHONPATH must be set in the environment for CopilotRunner to function properly.")

        prompt = (
            f"{prompt} If the task fails or you encounter an error, STOP "
            "immediately and report the error without trying other "
            "workarounds or methods."
        )
        # We use --allow-all to grant permissions required for non-interactive execution
        # and --no-color + --no-ask-user to force static automation.
        args = ["copilot", "-p", prompt, "--allow-all", "--no-color", "--no-ask-user"]

        print("Starting process...", flush=True)
        process = subprocess.Popen(
            args,
            cwd=workspace_path,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            stdin=subprocess.DEVNULL,
        )

        output_lines = []
        if process.stdout is None:
            raise RuntimeError("subprocess.Popen returned None stdout despite stdout=PIPE")
        for line in process.stdout:
            print(f"CLI OUTPUT: {line.strip()}", flush=True)
            output_lines.append(line)

        try:
            process.wait(timeout=_RUNNER_TIMEOUT)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()
            error_msg = f"\n[Copilot Runner Error] Timed out after {_RUNNER_TIMEOUT}s!"
            print(error_msg, flush=True)
            return error_msg

        return "".join(output_lines)


# ============================================================================
# Claude Code Runner
# ============================================================================


class ClaudeCodeRunner(AgentRunner):
    """
    Executes the Claude Code CLI in a headless, non-interactive environment
    for evaluating skill performance.
    """

    def run(self, prompt: str, workspace_path: str) -> str:
        """
        Executes a prompt via the Claude Code CLI and returns the console output.

        Enterprise OAuth is supported: when ``claude`` is on PATH and the user is
        authenticated via ``claude login``, no API key is required. ``ANTHROPIC_API_KEY``
        is only needed for CI/CD environments where OAuth is unavailable. This method
        therefore invokes the CLI unconditionally and lets the subprocess surface any
        auth error naturally.

        Args:
            prompt (str): The instructions to provide to the agent.
            workspace_path (str): The directory context for the agent's execution.

        Returns:
            str: The final stdout output generated by the agent.
        """
        print(f"\n[Claude Code Runner] Executing in {workspace_path}...")

        args = [
            "claude",
            "-p",
            prompt,
            "--output-format",
            "text",
            "--max-turns",
            os.environ.get("CLAUDE_MAX_TURNS", "25"),
            "--dangerously-skip-permissions",
            "--setting-sources",
            "user",
        ]

        env = os.environ.copy()
        env.pop("AWS_PROFILE", None)
        env.pop("AWS_DEFAULT_PROFILE", None)
        env["CI"] = "true"
        env["NO_COLOR"] = "1"

        process = subprocess.Popen(
            args,
            cwd=workspace_path,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            stdin=subprocess.DEVNULL,
        )

        output_lines = []
        if process.stdout is None:
            raise RuntimeError("subprocess.Popen returned None stdout despite stdout=PIPE")
        for line in process.stdout:
            output_lines.append(line)

        try:
            process.wait(timeout=_RUNNER_TIMEOUT)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()
            return f"\n[Claude Code Runner Error] Timed out after {_RUNNER_TIMEOUT}s!"

        if process.returncode != 0:
            return f"\n[Claude Code Runner Error] Return Code: {process.returncode}\nOutput: {''.join(output_lines)}"

        return "".join(output_lines)


