# ============================================================================
# Runner Registry and Factory
# ============================================================================

# Registry columns: (cli_name, runner_class, api_key_env_var, cli_sufficient)
# cli_sufficient=True means the CLI on PATH alone is enough (e.g. Claude with enterprise OAuth).
# cli_sufficient=False means a token/API key is required even if the binary exists.
_RUNNER_REGISTRY: list[tuple[str, type[AgentRunner], str, bool]] = [
    ("claude", ClaudeCodeRunner, "ANTHROPIC_API_KEY", True),  # CLI on PATH works via OAuth
    ("copilot", CopilotRunner, "COPILOT_GITHUB_TOKEN", False),  # headless needs token
    ("gemini", GeminiRunner, "GEMINI_API_KEY", False),  # headless needs token
    ("codex", CodexRunner, "OPENAI_API_KEY", False),  # headless needs token
]


def get_runner(runner_type: str | None = None) -> AgentRunner:
    """
    Factory function to retrieve an AgentRunner instance.

    If ``runner_type`` is provided, uses a direct lookup (backward compatibility).
    If ``runner_type`` is ``None``, auto-detects in the following order:

    1. ``EVAL_RUNNER`` env-var override.
    2. Registry priority scan:
       - For runners with ``cli_sufficient=True`` (Claude): the CLI binary on PATH is
         checked first (covers local dev with enterprise OAuth), then the API key env var
         (covers CI/CD).
       - For all other runners: only the API key env var is checked, because the CLI
         binary alone is insufficient for headless execution.

    Args:
        runner_type (str | None, optional): The name of the agent runner to load.
            If None, auto-detects from the environment. Defaults to None.

    Returns:
        AgentRunner: The instantiated agent evaluator.

    Raises:
        KeyError: If ``runner_type`` or ``EVAL_RUNNER`` specifies an unknown runner name.
        RuntimeError: If no suitable CLI binary or API key is found and runner_type is None.
    """
    _runners: dict[str, type[AgentRunner]] = {name: cls for name, cls, _, _ in _RUNNER_REGISTRY}

    if runner_type is not None:
        return _runners[runner_type]()

    # Check EVAL_RUNNER env var override first
    eval_runner_env = os.environ.get("EVAL_RUNNER")
    if eval_runner_env:
        return _runners[eval_runner_env]()

    # Auto-detect from registry in priority order
    for name, runner_cls, env_var, cli_sufficient in _RUNNER_REGISTRY:
        if cli_sufficient and shutil.which(name):
            return runner_cls()
        if os.environ.get(env_var):
            return runner_cls()

    raise RuntimeError(
        "No agent CLI or API key found. Set ANTHROPIC_API_KEY, COPILOT_GITHUB_TOKEN, GEMINI_API_KEY, or OPENAI_API_KEY, or install a supported CLI."
    )
